    private void generarSimulacionCombate() {
        if (controlador == null || controlador.getAventureros().isEmpty()) {
            txtAreaCombate.setText("No hay aventureros registrados para iniciar el combate.");
            return;
        }

        StringBuilder reporte = new StringBuilder();
        reporte.append("========== SIMULACIÓN DE COMBATE ==========\n\n");

        for (Aventurero av : controlador.getAventureros()) {
            reporte.append(av.simularCombate()).append("\n\n");
            reporte.append("--------------------------------------------------\n\n");
        }

        txtAreaCombate.setText(reporte.toString());
    }
